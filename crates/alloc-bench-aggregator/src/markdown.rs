//! REPORT.md emitter (D-09/D-10/D-11/D-12).
//!
//! Plan 01 shipped a deliberately minimal emitter (header + a `## Runs`
//! bullet list + `## Skipped inputs`). Plan 03 makes the report readable:
//!
//!   - Per-scenario allocator comparison tables with bold-and-✓ winner
//!     prefix and italic suspect notes (D-09 / AGG-04).
//!   - `## Docker runtimes` table with em-dash cells + Phase-5 backfill
//!     footnote (D-10 / AGG-05).
//!   - `## Allocator architectures` section embedding the four Mermaid
//!     constants in alphabetical order (D-11 / AGG-06).
//!   - `## Recommendations by workload` with data-derived rationale
//!     strings (D-12 / AGG-07) — calls `recommend::recommendations`.
//!
//! The Plan-01 `## Runs` bullet section is REMOVED — the per-scenario
//! tables subsume it.
//!
//! Byte-identical-output contract (D-09 / RESEARCH §Pitfall 5):
//!   - Sort everything alphabetically (BTreeMap / BTreeSet, never
//!     HashMap / HashSet).
//!   - Format throughput as `{:.1}` with the unit appended.
//!   - Format integers as `{}`, latency cells as `{} ns`, RSS as `{} kB`.
//!   - The single timestamp comment at the top is the only non-stable
//!     line — strippable in tests via first-line removal.

