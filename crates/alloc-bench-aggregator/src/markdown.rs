/// Public entry point — write `report/REPORT.md` against the loaded
/// outcome. Builds the buffer end-to-end via `build_report()` then
/// commits to disk. The two-step shape lets the byte-identical test
/// (Behavior 13) compare two builds without touching the filesystem.
pub fn write(
    outcome: &LoadOutcome,
    metas: &HashMap<(String, String), CellMeta>,
    out_dir: &Path,
) -> Result<()> {
    let buf = build_report(outcome, metas);
    let out_path = out_dir.join("REPORT.md");
    std::fs::write(&out_path, &buf).with_context(|| format!("writing {}", out_path.display()))?;
    Ok(())
}

/// Build the complete REPORT.md as a String. Factored from `write()` so
/// the byte-identical-output test can call it twice without disk I/O.
pub(crate) fn build_report(
    outcome: &LoadOutcome,
    metas: &HashMap<(String, String), CellMeta>,
) -> String {
    let mut buf = String::new();
    emit_header(&mut buf, outcome);
    emit_per_scenario_tables(&mut buf, &outcome.runs);
    emit_docker_runtimes_table(&mut buf, &outcome.runs, metas);
    emit_allocator_diagrams(&mut buf);
    emit_recommendations(&mut buf, &outcome.runs);
    if !outcome.skipped.is_empty() {
        emit_skipped(&mut buf, &outcome.skipped);
    }
    buf
}

fn emit_header(buf: &mut String, outcome: &LoadOutcome) {
    let timestamp = chrono::Utc::now().to_rfc3339();
    let _ = writeln!(
        buf,
        "<!-- schema_version: 1 · generated by alloc-bench-aggregator at {timestamp} -->"
    );
    let _ = writeln!(buf, "# alloc-bench REPORT");
    let _ = writeln!(buf);
    let cell_count = count_unique_cells(&outcome.runs);
    let _ = writeln!(
        buf,
        "**{} runs across {} cells.**",
        outcome.runs.len(),
        cell_count
    );
    let _ = writeln!(buf);
}

/// Per-scenario allocator comparison tables (D-09 / AGG-04 / D-11 / D-12).
///
/// One section per scenario in alphabetical order; rows alphabetical by
/// (allocator, env_label); winner row prefixed `**✓ {alloc}**`.
///
/// Multi-run decoration (D-11): when ≥2 runs share an `(alloc, env, scenario)`
/// triple, the throughput cell renders as `{median} ({min}..{max}, CV {N}%)`
/// with optional `⚠ high variance` (CV > 10%) and `⚠ suspect` flags
/// concatenated. When the cell has fewer than 2 runs, falls back to the
/// existing single-value `{:.1} {unit}` format with the suspect-note
/// italic — preserving the Phase-4 byte-identical-output contract for
/// every existing single-run-per-cell fixture.
fn emit_per_scenario_tables(buf: &mut String, runs: &[Run]) {
    // BTreeMap → alphabetical scenario iteration.
    let mut by_scenario: BTreeMap<&str, Vec<&Run>> = BTreeMap::new();
    for r in runs {
        by_scenario
            .entry(r.scenario.name.as_str())
            .or_default()
            .push(r);
    }

    for (scenario_name, scenario_runs) in by_scenario.iter() {
        // D-11 grouping pre-pass: build a BTreeMap<(alloc, env), Vec<f64>>
        // of throughput samples for this scenario. Used to decide whether
        // to emit the multi-run cell shape vs the single-value fallback.
        // BTreeMap is mandatory for alphabetical-iteration / byte-identical
        // output (RESEARCH §Pitfall 5).
        let mut by_cell: BTreeMap<(String, String), Vec<f64>> = BTreeMap::new();
        for r in scenario_runs.iter() {
            by_cell
                .entry((r.build.allocator.clone(), env_label(&r.env).to_string()))
                .or_default()
                .push(r.metrics.ticks_per_s);
        }

        let _ = writeln!(buf, "## {scenario_name}");
        let _ = writeln!(buf);
        let _ = writeln!(
            buf,
            "| allocator | throughput | p50 | p95 | p99 | p999 | peak RSS |"
        );
        let _ = writeln!(buf, "|---|---|---|---|---|---|---|");

        // Build a per-cell BTreeMap<(alloc, env), &Run> for emission rows.
        // Pick the FIRST run per (alloc, env) tuple (deterministic via
        // BTreeMap ordering once scenario_runs is sorted alpha) so we
        // don't emit duplicate rows when a fixture has multiple seeds.
        let mut row_keys: BTreeMap<(String, String), &Run> = BTreeMap::new();
        for r in scenario_runs.iter() {
            let key = (r.build.allocator.clone(), env_label(&r.env).to_string());
            row_keys.entry(key).or_insert(r);
        }

        // Winner index in iteration order: maximum CENTRAL TENDENCY (median
        // when ≥2 runs, mean fallback when n<2). The strict `>` keeps the
        // FIRST-seen winner on a tie, matching `recommend::pick_rationale_scenario`
        // and the dashboard's `renderReportMirrorTable`.
        let row_vec: Vec<((String, String), &Run)> =
            row_keys.iter().map(|(k, v)| (k.clone(), *v)).collect();
        let mut winner_idx: Option<usize> = None;
        for (i, (key, _)) in row_vec.iter().enumerate() {
            let tps = central_tendency(by_cell.get(key));
            match winner_idx {
                Some(j) => {
                    let prev = central_tendency(by_cell.get(&row_vec[j].0));
                    if tps > prev {
                        winner_idx = Some(i);
                    }
                }
                None => winner_idx = Some(i),
            }
        }

        for (idx, (key, r)) in row_vec.iter().enumerate() {
            let unit = r.scenario.unit.as_deref().unwrap_or("ticks/s");
            let alloc_cell = if Some(idx) == winner_idx {
                format!("**\u{2713} {}**", r.build.allocator)
            } else {
                r.build.allocator.clone()
            };
            let suspect = suspect_reason(&r.harness).is_some();
            // D-11 / D-12: multi-run shape when ≥2 runs in this cell.
            let throughput_cell = if let Some(samples) = by_cell.get(key) {
                if let Some(stats) = mr_aggregate(samples) {
                    format_throughput_cell(&stats, suspect)
                } else {
                    let mut s = format!("{:.1} {}", r.metrics.ticks_per_s, unit);
                    if let Some(reason) = suspect_reason(&r.harness) {
                        s.push(' ');
                        s.push_str(suspect_note(&reason));
                    }
                    s
                }
            } else {
                let mut s = format!("{:.1} {}", r.metrics.ticks_per_s, unit);
                if let Some(reason) = suspect_reason(&r.harness) {
                    s.push(' ');
                    s.push_str(suspect_note(&reason));
                }
                s
            };
            let _ = writeln!(
                buf,
                "| {alloc} | {tps} | {p50} ns | {p95} ns | {p99} ns | {p999} ns | {rss} kB |",
                alloc = alloc_cell,
                tps = throughput_cell,
                p50 = r.metrics.tick_latency_ns.p50,
                p95 = r.metrics.tick_latency_ns.p95,
                p99 = r.metrics.tick_latency_ns.p99,
                p999 = r.metrics.tick_latency_ns.p999,
                rss = r.metrics.peak_rss_kb,
            );
        }
        let _ = writeln!(buf);
    }
}

/// Central tendency for a set of throughput samples: median when ≥2 runs
/// (matching D-11), mean fallback for n<2 so winner-picking on existing
/// single-run-per-cell fixtures is byte-stable. Returns `0.0` when the
/// samples slice is empty (only possible if the caller passed `None`).
fn central_tendency(samples: Option<&Vec<f64>>) -> f64 {
    let Some(samples) = samples else { return 0.0 };
    if samples.is_empty() {
        return 0.0;
    }
    if let Some(s) = mr_aggregate(samples) {
        s.median
    } else {
        samples.iter().sum::<f64>() / samples.len() as f64
    }
}

/// Format a single throughput cell with multi-run decoration:
///   "100 (95..110, CV 5%)"
/// or with high-variance flag (CV > 10%):
///   "100 (90..130, CV 19% ⚠ high variance)"
/// or both flags concatenated (per CONTEXT.md `<specifics>` ¶5):
///   "100 (90..130, CV 19% ⚠ high variance ⚠ suspect)"
/// or with undefined CV (mean ≈ 0):
///   "0 (0..0, CV —)"
///
/// Output shape is canonical per RESEARCH §"Code Examples — Multi-run
/// aggregator integration" (lines 956-967 of 05-RESEARCH.md): all numbers
/// `{:.0}` rounded; CV `{:.0}%`; em-dash `\u{2014}` for undefined CV;
/// variance flag `\u{26A0} high variance`; suspect flag `\u{26A0} suspect`.
pub(crate) fn format_throughput_cell(s: &MultiRunStats, suspect: bool) -> String {
    let cv_str = match s.cv_pct {
        Some(cv) => format!("CV {cv:.0}%"),
        None => "CV \u{2014}".to_string(),
    };
    let variance_flag = if is_high_variance(s) {
        " \u{26A0} high variance"
    } else {
        ""
    };
    let suspect_flag = if suspect { " \u{26A0} suspect" } else { "" };
    format!(
        "{:.0} ({:.0}..{:.0}, {}{}{})",
        s.median, s.min, s.max, cv_str, variance_flag, suspect_flag
    )
}

/// Docker runtimes table (D-10 / AGG-05 / D-13).
///
/// When `metas` is empty (default `--meta` flag), every value cell renders
/// as em-dash — preserving Phase-4 byte-identical-output. When `metas` is
/// non-empty (CI populated it via `docker image inspect --format '{{.Size}}'`),
/// each env row's `image_size_mb` cell is filled from the matching sidecar
/// (1 decimal place); cells without a meta sidecar fall back to em-dash.
///
/// Join semantics: a meta sidecar carries the **short** env name
/// (e.g. `"alpine"`), but `env_label` here is the docker_image tag
/// (e.g. `"alloc-bench:jemalloc-alpine"`). We synthesize the expected
/// docker_image as `format!("alloc-bench:{}-{}", meta.alloc, meta.env)`
/// and look that up against the row's env_label. This avoids parsing
/// the docker tag on the read side.
fn emit_docker_runtimes_table(
    buf: &mut String,
    runs: &[Run],
    metas: &HashMap<(String, String), CellMeta>,
) {
    let envs: BTreeSet<String> = runs.iter().map(|r| env_label(&r.env).to_string()).collect();

    // Build a reverse index: docker_image_tag → image_size_mb (alphabetical
    // tiebreak via BTreeMap when multiple metas synthesize the same tag,
    // which shouldn't happen in practice but the order is deterministic).
    let mut by_docker_image: BTreeMap<String, f64> = BTreeMap::new();
    for ((alloc, env_short), meta) in metas.iter() {
        let synth = format!("alloc-bench:{alloc}-{env_short}");
        by_docker_image.insert(synth, meta.image_size_mb);
    }

    let _ = writeln!(buf, "## Docker runtimes");
    let _ = writeln!(buf);
    let _ = writeln!(
        buf,
        "| env | image_size_mb | build_time_s | run_overhead_pct |"
    );
    let _ = writeln!(buf, "|---|---|---|---|");
    for env in envs.iter() {
        let size_cell = match by_docker_image.get(env) {
            Some(mb) => format!("{mb:.1}"),
            None => "\u{2014}".to_string(),
        };
        let _ = writeln!(buf, "| {env} | {size_cell} | \u{2014} | \u{2014} |");
    }
    let _ = writeln!(buf);
    if metas.is_empty() {
        let _ = writeln!(
            buf,
            "*image_size_mb / build_time_s / run_overhead_pct populated by Phase 5 CI via docker inspect (REPR-03).*"
        );
    } else {
        let _ = writeln!(
            buf,
            "*image_size_mb populated from CI sidecar (D-13); em-dash for cells without meta sidecars.*"
        );
    }
    let _ = writeln!(buf);
}

/// Allocator architectures section (D-11 / AGG-06). Iterates
/// `diagrams::ALL_DIAGRAMS` in alphabetical order (jemalloc, mallocng,
/// mimalloc, ptmalloc) and emits each Mermaid constant verbatim under
/// its own `### {name}` subsection.
fn emit_allocator_diagrams(buf: &mut String) {
    let _ = writeln!(buf, "## Allocator architectures");
    let _ = writeln!(buf);
    for (name, body) in ALL_DIAGRAMS.iter() {
        let _ = writeln!(buf, "### {name}");
        let _ = writeln!(buf);
        let _ = writeln!(
            buf,
            "Source: see crates/alloc-bench-aggregator/src/diagrams.rs for upstream reference."
        );
        // The constant body opens with a leading newline + fenced mermaid
        // block (Task 1 baked the leading newline in deliberately).
        buf.push_str(body);
        let _ = writeln!(buf);
    }
}

/// Recommendations by workload (D-12 / AGG-07). Calls
/// `recommend::recommendations` and renders one row per Recommendation.
/// The rationale cell is emitted verbatim — including the data-derived
/// `+{delta:.1}%` substring and the optional `*(suspect)*` annotation.
/// Hardcoded prose is forbidden — the recommend module is the SINGLE
/// authority for these strings (RESEARCH §Pitfall 7).
fn emit_recommendations(buf: &mut String, runs: &[Run]) {
    let recs = recommendations(runs);
    let _ = writeln!(buf, "## Recommendations by workload");
    let _ = writeln!(buf);
    let _ = writeln!(buf, "| Workload | Recommended | Rationale |");
    let _ = writeln!(buf, "|---|---|---|");
    for r in recs.iter() {
        let _ = writeln!(buf, "| {} | {} | {} |", r.class, r.allocator, r.rationale);
    }
    let _ = writeln!(buf);
}

fn emit_skipped(buf: &mut String, skipped: &[crate::loader::SkippedFile]) {
    let _ = writeln!(buf, "## Skipped inputs");
    let _ = writeln!(buf);
    let mut sorted: Vec<&crate::loader::SkippedFile> = skipped.iter().collect();
    sorted.sort_by(|a, b| a.path.cmp(&b.path));
    for s in sorted {
        let _ = writeln!(buf, "- {}: {}", s.path.display(), s.reason);
    }
    let _ = writeln!(buf);
}

/// Stable label for an env (Docker image tag if present, else "host").
/// Used both for cell-counting and for sorted bullet emission. Matches
/// the html.rs unique-cell counter so the two stay coherent.
pub(crate) fn env_label(env: &Env) -> &str {
    env.docker_image.as_deref().unwrap_or("host")
}

/// Count of unique (allocator, env_label) cells across all runs.
fn count_unique_cells(runs: &[Run]) -> usize {
    let mut set = BTreeSet::new();
    for r in runs {
        set.insert((r.build.allocator.as_str(), env_label(&r.env)));
    }
    set.len()
}

/// Which D-07 suspect predicate(s) fire for this harness. Return values
/// match `is_suspect(h) == reason.is_some()` exactly — keep them in
/// lockstep so REPORT.md's italic notes can't drift from the HTML
/// dashboard's badges.
enum SuspectReason {
    LowSamples,
    ShortWarmup,
    Both,
}

fn suspect_reason(h: &HarnessInfo) -> Option<SuspectReason> {
    let low = h.samples_count < 10_000;
    let short = h.warmup_duration_s < 5.0;
    let reason = match (low, short) {
        (true, true) => Some(SuspectReason::Both),
        (true, false) => Some(SuspectReason::LowSamples),
        (false, true) => Some(SuspectReason::ShortWarmup),
        (false, false) => None,
    };
    // Single-source-of-truth sanity check: this classifier and the
    // canonical D-07 predicate `crate::html::is_suspect` must agree.
    // If they ever drift, REPORT.md italic notes and the dashboard ⚠
    // badges would split-brain on which runs are flagged.
    debug_assert_eq!(reason.is_some(), is_suspect(h));
    reason
}

fn suspect_note(reason: &SuspectReason) -> &'static str {
    match reason {
        SuspectReason::LowSamples => "*(\u{26A0} suspect: low samples)*",
        SuspectReason::ShortWarmup => "*(\u{26A0} suspect: short warmup)*",
        SuspectReason::Both => "*(\u{26A0} suspect: low samples, short warmup)*",
    }
}

