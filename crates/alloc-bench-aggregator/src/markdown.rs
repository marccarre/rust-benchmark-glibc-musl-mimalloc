//! Minimal REPORT.md emitter for Plan 01 (D-09 / UI-SPEC line 167-173).
//!
//! Plan 01 ships a deliberately minimal emitter:
//!   - Single timestamp comment at top (UI-SPEC line 168).
//!   - `# alloc-bench REPORT` H1.
//!   - Run-count summary line.
//!   - `## Runs` section: alphabetically-sorted bullet list.
//!   - `## Skipped inputs` section ONLY when partial failures occurred (D-08).
//!
//! Plan 02 adds per-scenario allocator tables, suspect badges, A/B diff text.
//! Plan 03 adds Mermaid allocator diagrams + Recommendations section.
//!
//! Byte-identical-output contract (D-09 / RESEARCH §Pitfall 5):
//!   - Sort everything before emission.
//!   - Use `BTreeMap`, never `HashMap`, for any per-key aggregation.
//!   - Format integers as `{}`, throughput as `{:.1}`.
//!   - Single timestamp at top — strippable in snapshot tests via regex.

use std::fmt::Write as _;
use std::path::Path;

use alloc_bench_core::output::{Env, Run};
use anyhow::{Context, Result};

use crate::loader::LoadOutcome;

pub fn write(outcome: &LoadOutcome, out_dir: &Path) -> Result<()> {
    let mut buf = String::new();
    emit_header(&mut buf, outcome)?;
    emit_runs(&mut buf, &outcome.runs)?;
    if !outcome.skipped.is_empty() {
        emit_skipped(&mut buf, &outcome.skipped)?;
    }
    let out_path = out_dir.join("REPORT.md");
    std::fs::write(&out_path, &buf).with_context(|| format!("writing {}", out_path.display()))?;
    Ok(())
}

fn emit_header(buf: &mut String, outcome: &LoadOutcome) -> Result<()> {
    let timestamp = chrono::Utc::now().to_rfc3339();
    writeln!(
        buf,
        "<!-- schema_version: 1 · generated by alloc-bench-aggregator at {timestamp} -->"
    )?;
    writeln!(buf, "# alloc-bench REPORT")?;
    writeln!(buf)?;
    let cell_count = count_unique_cells(&outcome.runs);
    writeln!(
        buf,
        "**{} runs across {} cells.**",
        outcome.runs.len(),
        cell_count
    )?;
    writeln!(buf)?;
    Ok(())
}

fn emit_runs(buf: &mut String, runs: &[Run]) -> Result<()> {
    writeln!(buf, "## Runs")?;
    writeln!(buf)?;
    // Sort by (allocator, env_label, scenario.name) for byte-identical
    // output. We borrow here so we don't mutate the caller's runs vec.
    let mut sorted: Vec<&Run> = runs.iter().collect();
    sorted.sort_by(|a, b| {
        let ka = (
            a.build.allocator.as_str(),
            env_label(&a.env),
            a.scenario.name.as_str(),
        );
        let kb = (
            b.build.allocator.as_str(),
            env_label(&b.env),
            b.scenario.name.as_str(),
        );
        ka.cmp(&kb)
    });
    for r in sorted {
        let unit = r.scenario.unit.as_deref().unwrap_or("ticks/s");
        writeln!(
            buf,
            "- {alloc} · {env} · {scen}: {tps:.1} {unit}",
            alloc = r.build.allocator,
            env = env_label(&r.env),
            scen = r.scenario.name,
            tps = r.metrics.ticks_per_s,
            unit = unit
        )?;
    }
    writeln!(buf)?;
    Ok(())
}

fn emit_skipped(buf: &mut String, skipped: &[crate::loader::SkippedFile]) -> Result<()> {
    writeln!(buf, "## Skipped inputs")?;
    writeln!(buf)?;
    let mut sorted: Vec<&crate::loader::SkippedFile> = skipped.iter().collect();
    sorted.sort_by(|a, b| a.path.cmp(&b.path));
    for s in sorted {
        writeln!(buf, "- {}: {}", s.path.display(), s.reason)?;
    }
    writeln!(buf)?;
    Ok(())
}

/// Stable label for an env (Docker image tag if present, else "host").
/// Used both for cell-counting and for sorted bullet emission. Matches
/// the html.rs unique-cell counter so the two stay coherent.
pub(crate) fn env_label(env: &Env) -> &str {
    env.docker_image.as_deref().unwrap_or("host")
}

/// Count of unique (allocator, env_label) cells across all runs.
fn count_unique_cells(runs: &[Run]) -> usize {
    use std::collections::BTreeSet;
    let mut set = BTreeSet::new();
    for r in runs {
        set.insert((r.build.allocator.as_str(), env_label(&r.env)));
    }
    set.len()
}
